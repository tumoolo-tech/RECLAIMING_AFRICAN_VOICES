/** Sources still carrying a rights debt — what docs/16 has to chase. */
export function unclearedSources(): MediaSource[] {
  return mediaSources.filter((s) => s.status === "unverified" || s.status === "must-replace");
}

/** Does this source claim `file` (a path relative to app/assets/, with "/" separators)?
 *
 *  Neither a directory nor an extension claim reaches into a subdirectory: `journey/` does not
 *  silently swallow `journey/clips/`, which belongs to somebody else entirely. That is the whole
 *  point — a permission granted for one work must not quietly extend to the next file dropped
 *  nearby. `media-rights.test.ts` proves it by walking the real tree. */
export function sourceClaims(source: MediaSource, file: string): boolean {
  return source.paths.some((p) => {
    if (p.endsWith("/")) return file.startsWith(p) && !file.slice(p.length).includes("/");
    const star = p.indexOf("/*.");
    if (star !== -1) {
      const dir = p.slice(0, star + 1);
      const ext = p.slice(star + 2);
      return file.startsWith(dir) && !file.slice(dir.length).includes("/") && file.endsWith(ext);
    }
    return file === p;
  });
}
