// Who owns the media this app ships, and whether we are allowed to ship it (issue #35).
//
// THE GAP THIS FILLS. The repo already records rights twice, and well: books carry `Module.rights`
// (issue #34, shown on About the Sources), and each place photograph carries `credit` + `licence` +
// `source` in places.ts — "credit is a licence obligation, not a courtesy". Everything else — the
// whole soundtrack, the three films, the poems, the anthem, the animal sounds, every photograph of a
// real person — shipped with no licence recorded anywhere.
//
// ATTRIBUTION IS NOT A LICENCE. Several of these assets ARE credited: `audioBy: "Jessica Mbangeni"`,
// `anthemBy: "Stellenbosch University Choir"`, a footer card linking the African Tribe Echoes
// channel. Someone thought carefully about naming people. But naming a performer does not grant the
// right to bundle their performance, and a YouTube credit is not a YouTube licence — the terms do
// not permit redistribution. Crediting and clearing are two different obligations; this file is the
// second one.
//
// WHY IT IS KEYED ON SOURCE WORKS, NOT FILES. 231 audio and video files come from about a dozen
// works: one track sliced into 202 clips, three films, three poems, one anthem, 22 animal sounds.
// One row per file would be 573 rows of mostly-duplicated truth, and a rights question is asked of a
// work, not of a byte range. Each entry claims the files it produced; `media-rights.test.ts` walks
// app/assets and fails if any file is claimed by nobody, or if a claimed count drifts.
//
// THE DECISION (2026-09-27, Tumo): unverified media KEEPS PLAYING while permission is requested,
// rather than being switched off first. The soundtrack is the app's ambience, and silencing it
// before anyone has said no is a large, certain loss against a risk nobody has measured. What
// changes today is that the repo can state exactly what it ships and on what basis — the requests
// are drafted in docs/16-media-rights-register.md and are Tumo's to send. `unverified` here means
// "we do not know that we may use this". It is a debt, not a clearance.
//
// Pure data — no require(), so it loads under `node --test` (the SP-032 trap that keeps provinces.ts
// un-importable). Components resolve the real assets; this file only names paths.

export type MediaRightsStatus =
  /** Someone has the right to ship it: public domain, an explicit licence, or our own work. */
  | "cleared"
  /** Machine-generated by this project (Pollinations, Gemini, ElevenLabs). Not a third party's work,
   *  so there is no licence to obtain — but it must be labelled in-app as an interpretation, never
   *  as evidence, which is its own obligation (AGENTS.md §4). */
  | "generated"
  /** We do not know that we may use it. The honest default, and a debt. */
  | "unverified"
  /** We know we may NOT use it, and it is still here. Nothing is in this state today; it exists so
   *  that a refusal has somewhere to be recorded that is louder than `unverified`. */
  | "must-replace";

export type MediaSource = {
  /** Stable slug. */
  id: string;
  /** The work, as its maker would name it. */
  title: string;
  /** Who owns it. "[NEEDS SOURCE]" when the repo does not record it — never a guess. */
  holder: string;
  /** Where it came from, checkable where possible. */
  origin: string;
  status: MediaRightsStatus;
  /** Why that status — the reasoning, so a reader can disagree with it. */
  basis: string;
  /**
   * What actually clears it: a licence name and URL, a public-domain calculation, or a reference to
   * the written permission. REQUIRED when `status` is "cleared", and the test enforces that.
   *
   * It is a separate field rather than a sentence in `basis` because prose cannot be checked. The
   * first version of this guard searched `basis` for the word "permission" — which the soundtrack's
   * own text already contains, in the sentence "Permission not yet requested". A row could be
   * flipped to "cleared" and the test would still pass. Evidence has to be a thing you either have
   * or do not.
   */
  evidence?: string;
  /** What must be shown to a reader, when something must. */
  attribution?: string;
  /** Paths under app/assets/ that this work produced. Three shapes, none of which reach into a
   *  subdirectory — a nested folder belongs to whoever names it, so nothing is covered by accident:
   *
   *    "flags/"           every file directly in flags/
   *    "journey/*.webp"   only the .webp directly in journey/ — the films there are somebody else's
   *    "audio/youth.mp3"  that one file
   *
   *  The middle shape exists because assets/journey/ holds both AI interpretations and three
   *  third-party films. One directory, two completely different rights answers. */
  paths: string[];
  /** How many files those paths cover. Pinned so that adding a 203rd clip is a failing test rather
   *  than a silent extension of somebody else's permission. */
  count: number;
};

